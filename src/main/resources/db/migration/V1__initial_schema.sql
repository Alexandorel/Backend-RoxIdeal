-- Schema as Hibernate had created it before Flyway was introduced.
-- Constraint names are kept identical to the existing dev DB so later migrations can reference them on every DB.

CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name  VARCHAR(255) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    phone      VARCHAR(255) NOT NULL,
    role       VARCHAR(255) NOT NULL,
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT ukt8o6pivur7nn124jehx7cygw5 UNIQUE (name)
);

-- unit and category_id are nullable: rows existed before these columns were added
CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(2000),
    image_url   VARCHAR(255),
    name        VARCHAR(255) NOT NULL,
    price       NUMERIC(38, 2) NOT NULL,
    stock       INTEGER NOT NULL,
    unit        VARCHAR(255),
    category_id BIGINT,
    CONSTRAINT products_unit_check CHECK (unit IN ('BUC', 'KG', 'M', 'MP', 'L')),
    CONSTRAINT fkog2rp4qthbtt2lfyhfo32lsw9 FOREIGN KEY (category_id) REFERENCES categories (id)
);
